#!/usr/bin/env python3
"""pipeline-canary-20261106.py — daily regression canary (DESIGN §7, NOT installed).

Dispatches a fixed small code task through pipeline-dispatch, waits up to
20 min for DONE, writes a receipt, exits 0 only on DONE.
Intended cron (NOT installed in this build, needs chairman approval):
  0 8 * * * /home/ubuntu/ai-team/scripts/pipeline-canary-20261106.py
"""
import datetime
import json, os, subprocess, sys, time

BASE = "/home/ubuntu/ai-team"
GEN = BASE + "/scripts/code-gen-20261106.py"
DISPATCH = BASE + "/scripts/pipeline-dispatch-20261106.py"
OUT = BASE + "/state/pipeline-formal-20261106"


def _dsn():
    for line in open(BASE + "/state/.cq-dsn"):
        line = line.strip()
        if line.startswith("CQ_DSN="):
            return line[len("CQ_DSN="):].strip().strip('"').strip("'")
    return ""


def main():
    # 2026-11-06 fix (long-task-heartbeat regression): the fixed task_id made
    # the canary a one-shot - dispatch refuses duplicates, so every re-run
    # failed at dispatch. Suffix with UTC run time; each run is a fresh task.
    tid = "pipeline-canary-20261106d-" + datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M")
    spec = {"task_id": tid, "model_primary": "glm-4-flash-cc",
            "model_fallback": "qwen3.8-flash",
            "system": "You write small Python utilities. Output only ===FILE: blocks.",
            "prompt": ("Write add_one.py with a function add_one(n) returning n+1, "
                       "and test_add_one.py with pytest tests for 0, 1, -5. "
                       "Use ===FILE: add_one.py === ... ===END=== and "
                       "===FILE: test_add_one.py === ... ===END===."),
            "max_tokens": 4000, "timeout_s": 180}
    sp = os.path.join(OUT, "canary-spec-%s.json" % tid)
    os.makedirs(OUT, exist_ok=True)
    json.dump(spec, open(sp, "w"))
    outdir = os.path.join(BASE, "state/code-gen-20261106/out", tid)
    r = subprocess.run(["python3", GEN, "--spec", sp, "--out-dir", outdir],
                       capture_output=True, text=True, timeout=300)
    if r.returncode != 0:
        print("CANARY_FAIL code-gen rc=%d %s" % (r.returncode, (r.stdout or "")[:300])); return 1
    contract = {"task_id": tid, "task_type": "code",
                "format": "PULLONCE-BUNDLE-V1",
                "five_part": {"goal": "Pipeline canary: add_one utility + pytest, generated by hub code-gen.",
                              "constraint": "stdlib only; pytest on worker-1; verifier DONE",
                              "stop_when": "pytest green on worker-1, verifier DONE",
                              "must_not": "no fake DONE; no manual SQL; no manual file delivery",
                              "report": "receipt in state/pipeline-formal-20261106/"},
                "input": "Pipeline canary: add_one utility + pytest, generated by hub code-gen.",
                "output_path": os.path.join(outdir, "add_one.py"),
                "evidence": "pytest on worker-1 + verifier DONE, receipt in state/pipeline-formal-20261106/",
                "pass_line": "pytest green on worker-1, verifier DONE, no manual steps.",
                "fail_action": "RETRY_WAIT with verbatim reason, no manual DONE flip.",
                "verifier": "c2-verifier + pipeline contract test",
                "forbidden": ["no fake DONE", "no manual SQL", "no manual file delivery"],
                "workdir": "~/code-agent-pilot/workdir/pipeline-canary",
                # cutover51 strict fields (W5.2 / W3.4)
                "test_command": ["python3", "-m", "pytest", "-q"],
                "test_baseline_seconds": 60,
                "allowed_dependencies": [],
                "estimated_seconds": 600,
                "code_files": ["scripts/taskcontract_gate.py"],
                "evidence_files": ["state/cutover-20261110.log"]}
    cp = os.path.join(OUT, "canary-contract-%s.json" % tid)
    json.dump(contract, open(cp, "w"))
    # Cutover51 W1: the canary no longer uses --allow-no-gate. It must pass
    # dispatch-gate-hub like any formal task, so the harness generates the
    # four artifacts itself each run (PLAN + verdict + preflight + contract).
    # CAVEAT: the verdict here is self-issued by the regression harness
    # (labeled synthetic below); it proves pipeline mechanics, NOT
    # independent review. Formal tasks still need a real butler verdict.
    plan_dir = os.path.join(BASE, "state", tid)
    os.makedirs(plan_dir, exist_ok=True)
    with open(os.path.join(plan_dir, "PLAN-canary.md"), "w") as f:
        f.write("# 背景\nPipeline daily regression canary (synthetic).\n\n"
                "# 目标\nDispatch add_one through the full pipeline and reach verifier DONE.\n\n"
                "# 不做\nNo manual DONE flip, no manual SQL, no manual file delivery.\n\n"
                "# 方案选项\nA) pipeline-dispatch with gates (chosen). B) direct insert (refused: bypasses gates).\n\n"
                "# 评估标准（contract）\npytest green on worker-1, verifier DONE, receipt in state/pipeline-formal-20261106/.\n\n"
                "# 风险\nGate changes may refuse the synthetic contract; codegen seat may be busy (deferred, not failure).\n\n"
                "# 回滚\nDelete the canary task row; re-run the canary; rollback-all.sh restores pre-cutover gates.\n\n"
                "# 需拍板点\nNone: synthetic regression only, no spend, no external publish.\n")
    verdict_dir = os.path.join(BASE, "ceo-seat", "state", "butler-verdicts")
    os.makedirs(verdict_dir, exist_ok=True)
    with open(os.path.join(verdict_dir, "%s.json" % tid), "w") as f:
        json.dump({"verdict": "通过", "task": tid,
                   "note": "SYNTHETIC regression-harness verdict (self-issued by pipeline-canary); proves pipeline mechanics only, not independent review.",
                   "ts": datetime.datetime.now(datetime.timezone.utc).isoformat()}, f, ensure_ascii=False)
    pre = subprocess.run(["python3", BASE + "/scripts/preflight-gate-20261107.py",
                          "--task", tid, "--record",
                          "--q1", "hub: pipeline-dispatch, dispatch-gate-hub, taskcontract_gate (existing scripts, no new dependency)",
                          "--q2", "existing hub scripts, no external package",
                          "--q3", "reuse existing pipeline; no new tool",
                          "--q4", "canary exits 0 only on verifier DONE; timeout 20 min",
                          "--queue3"], capture_output=True, text=True, timeout=30)
    if pre.returncode != 0:
        print("CANARY_FAIL preflight record rc=%d %s" % (pre.returncode, (pre.stdout or "")[:300])); return 1
    r = subprocess.run(["python3", DISPATCH, "--contract", cp],
                       capture_output=True, text=True, timeout=900)
    print((r.stdout or "") + (r.stderr or ""), end="")
    if r.returncode != 0:
        print("CANARY_FAIL dispatch rc=%d" % r.returncode); return 1
    import psycopg
    deadline = time.time() + 20 * 60
    with psycopg.connect(_dsn()) as conn:
        while time.time() < deadline:
            with conn.cursor() as cur:
                cur.execute("SELECT status FROM central_tasks WHERE payload->>'task_id'=%s", (tid,))
                row = cur.fetchone()
            if row and row[0] == "DONE":
                print("CANARY_OK task=%s DONE" % tid); return 0
            if row and row[0] in ("QUARANTINED",):
                print("CANARY_FAIL task=%s status=%s" % (tid, row[0])); return 1
            time.sleep(60)
    print("CANARY_FAIL timeout, last status=%s" % (row[0] if row else None)); return 1


if __name__ == "__main__":
    sys.exit(main())
