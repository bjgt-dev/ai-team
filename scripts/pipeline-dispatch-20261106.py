#!/usr/bin/env python3
"""pipeline-dispatch-20261106.py — formal dispatch wrapper (DESIGN §5).

One command: dispatch-gate -> [hub codegen, code tasks only] -> INSERT READY
-> auto-provision -> receipt.
Dispatch-gate (2026-11-07 wired): before INSERT, run
scripts/dispatch-gate-hub.py <task_id> (PLAN + contract + verdict +
preflight, four checks, exit 0 pass / 2 refuse). Refusal stops the
dispatch (exit 1, nothing inserted).
Hub codegen (2026-11-10, worker-1 leg fix): if ENABLE_HUB_CODEGEN=1 and the
contract task_type is code, run scripts/pipeline-codegen-20261110.py BEFORE
INSERT. It generates code + tests on the hub (ceo-opencode.sh) and writes a
receipt; only then is the task inserted READY and provisioned. Codegen
failure (rc 1) aborts dispatch, nothing inserted. Codegen SKIP (rc 2, butler
seat busy) aborts dispatch with exit 3 (deferred, NOT a failure, no retry
consumed). Flag off (default) = exactly the old behavior (rollback = unset
the flag).
  --allow-no-gate: skip the dispatch gate. ONLY for the synthetic daily
  regression canary (pipeline-canary-20261106.py), which has no PLAN /
  verdict / preflight by design. Any other caller must pass the gate.
Usage:
  python3 scripts/pipeline-dispatch-20261106.py --contract <contract.json>
      [--manifest <manifest.json>] [--allow-no-gate]
If --manifest is omitted, it is built from the contract: dependencies
(contract.dependencies: [{hub_path, worker_rel}]) plus the code-gen
receipt (state/code-gen-20261106/out/<task_id>/receipt.json) if present.
Exit 0 = inserted READY AND provision ok; 1 = gate refused / codegen failed;
2 = provision failed (row stays READY, receipt records it, no claim is
forced); 3 = codegen SKIP (seat busy, deferred, nothing inserted).
"""
import argparse, json, os, subprocess, sys, time

BASE = "/home/ubuntu/ai-team"
DISPATCH = BASE + "/scripts/dispatch_task.py"
PROVISION = BASE + "/scripts/pipeline-provision-20261106.py"
CODEGEN = BASE + "/scripts/pipeline-codegen-20261110.py"
RECEIPT_DIR = BASE + "/state/pipeline-formal-20261106"


def _ts():
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _build_manifest(contract):
    files = []
    for d in contract.get("dependencies", []) or []:
        files.append({"hub_path": d["hub_path"], "worker_rel": d["worker_rel"]})
    # code-gen receipt, if the task was generated by code-gen-20261106.py
    # or pipeline-codegen-20261110.py
    tid = contract.get("task_id", "")
    rp = os.path.join(BASE, "state/code-gen-20261106/out", tid, "receipt.json")
    if os.path.exists(rp):
        rec = json.load(open(rp))
        outdir = os.path.join(BASE, "state/code-gen-20261106/out", tid)
        # pipeline-codegen receipts carry base_dir (state/codegen-workdir/<name>/)
        # and relative paths; code-gen-20261106.py receipts use outdir + relative.
        base = rec.get("base_dir") or outdir
        wd = (contract.get("workdir") or "~/code-agent-pilot/workdir").replace("~/", "")
        for f in rec.get("files", []):
            files.append({"hub_path": os.path.join(base, f["path"]),
                          "worker_rel": wd + "/" + f["path"]})
    # contract output_path, if it is a hub file
    op = contract.get("output_path", "")
    if op and os.path.exists(op):
        files.append({"hub_path": op, "worker_rel": "code-agent-pilot/workdir/" + os.path.basename(op)})
    # de-duplicate by hub_path, sorted
    seen, out = set(), []
    for f in sorted(files, key=lambda x: x["hub_path"]):
        if f["hub_path"] not in seen:
            seen.add(f["hub_path"]); out.append(f)
    return {"task_id": tid, "files": out}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--contract", required=True)
    ap.add_argument("--manifest")
    ap.add_argument("--allow-no-gate", action="store_true",
                    help="skip dispatch-gate-hub; synthetic canary only")
    a = ap.parse_args()
    contract = json.load(open(a.contract))
    tid = contract.get("task_id", "unknown")
    if not a.allow_no_gate:
        g = subprocess.run(["python3", BASE + "/scripts/dispatch-gate-hub.py", tid],
                           capture_output=True, text=True, timeout=120)
        print((g.stdout or "") + (g.stderr or ""), end="")
        if g.returncode != 0:
            print("PIPELINE_DISPATCH_FAIL dispatch-gate rc=%d task=%s" % (g.returncode, tid))
            return 1
        print("PIPELINE_DISPATCH_GATE_PASS task=%s" % tid)
    else:
        print("PIPELINE_DISPATCH_GATE_SKIPPED task=%s reason=synthetic-canary-only" % tid)
    # Hub codegen (2026-11-10): code tasks only, flag-gated, before INSERT.
    # No receipt / no valid codegen => worker-1 would claim an empty workdir
    # and fail pytest_exit_5. So a code task is only INSERTed once its code
    # exists on the hub.
    if os.environ.get("ENABLE_HUB_CODEGEN", "") == "1" and contract.get("task_type") == "code":
        cg = subprocess.run(["python3", CODEGEN, "--contract", a.contract],
                            capture_output=True, text=True, timeout=720)
        print((cg.stdout or "") + (cg.stderr or ""), end="")
        if cg.returncode == 2:
            print("PIPELINE_DISPATCH_DEFERRED codegen_skip task=%s (seat busy, retry later, nothing inserted)" % tid)
            return 3
        if cg.returncode != 0:
            print("PIPELINE_DISPATCH_FAIL codegen rc=%d task=%s (nothing inserted)" % (cg.returncode, tid))
            return 1
        print("PIPELINE_DISPATCH_CODEGEN_OK task=%s" % tid)
    r = subprocess.run(["python3", DISPATCH, "--contract", a.contract],
                       capture_output=True, text=True, timeout=120)
    print((r.stdout or "") + (r.stderr or ""), end="")
    if r.returncode != 0:
        print("PIPELINE_DISPATCH_FAIL gate/insert rc=%d" % r.returncode)
        return 1
    man = json.load(open(a.manifest)) if a.manifest else _build_manifest(contract)
    mp = os.path.join(RECEIPT_DIR, "manifest-%s.json" % str(tid)[:8])
    os.makedirs(RECEIPT_DIR, exist_ok=True)
    json.dump(man, open(mp, "w"), ensure_ascii=False, indent=2)
    if not man.get("files"):
        print("PIPELINE_DISPATCH_OK task=%s inserted READY, no files to provision" % tid)
        return 0
    r2 = subprocess.run(["python3", PROVISION, "--manifest", mp, "--receipt-dir", RECEIPT_DIR],
                        capture_output=True, text=True, timeout=600)
    print((r2.stdout or "") + (r2.stderr or ""), end="")
    if r2.returncode != 0:
        print("PIPELINE_DISPATCH_FAIL provision rc=%d (row stays READY)" % r2.returncode)
        return 2
    print("PIPELINE_DISPATCH_OK task=%s inserted READY + provisioned" % tid)
    return 0


if __name__ == "__main__":
    sys.exit(main())
